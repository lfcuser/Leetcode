    37. Sudoku Solver

    Write a program to solve a Sudoku puzzle by filling the empty cells.
    
    A sudoku solution must satisfy all of the following rules:
    
        Each of the digits 1-9 must occur exactly once in each row.
        Each of the digits 1-9 must occur exactly once in each column.
        Each of the digits 1-9 must occur exactly once in each of the 9 3x3 sub-boxes of the grid.
    
    The '.' character indicates empty cells.
*/
class Solution
{
    const NUMS = ['1','2','3','4','5','6','7','8','9'];
    /**
     * @param string[][] $board
     * @return NULL
     */
    function solveSudoku(&$board)
    {
        $this->solve($board);
    }
    
    function solve(&$board, $s_row = 0, $s_col = 0)
    {
        for ($i = $s_row; $i < 9; $i++) {
            for ($j = $s_col; $j < 9; $j++) {
                if ($board[$i][$j] !== '.') {
                    continue;
                }
                foreach (self::NUMS as $num) {
                    if ($this->isValid($board, $num, $i, $j)) {
                        $board[$i][$j] = $num;
                        if ($j === 8) {
                            $s_row = $i+1;
                            $s_col = 0;
                        }

                        if ($this->solve($board, $s_row, $s_col)) {
                            return true;
                        }
                        $board[$i][$j] = '.';
                    }
                }
                return false;
            }
        }
        return true;
    }
    
    function isValid($board, $num, $row, $col)
    {
        if (in_array($num, $board[$row])) {
            return false;
        }
        for ($i = 0; $i < 9; $i++) {
            if ($board[$i][$col] === $num) {
                return false;
            }
        }
        $startRow = $row - ($row % 3);
        $startCol = $col - ($col % 3);
        for ($i = 0; $i < 3; $i++) {
            if (
                $num === $board[$i + $startRow][0 + $startCol]
                || $num === $board[$i + $startRow][1 + $startCol]
                || $num === $board[$i + $startRow][2 + $startCol]
            ) {
                return false;
            }
        }
        return true;
    }
}

function printBoard($arr)
{
    $l = 9;
    for ($i = 0; $i < $l; $i++) {
        for ($j = 0; $j < $l; $j++) {
            echo sprintf('|%s|', $arr[$i][$j]);
        }
        echo "\n";
    }
}

